class CandidateAction:
    """
    Formal typed proposal generated by a probabilistic model or planner.
    Subject to strict dual-gate reduction before it can ever become committable.
    """
    def __init__(
        self,
        action_id: str,
        source_state_version: StateVersion,
        generated_at_ns: int,
        valid_until_ns: int,
        action_type: str,
        target_tenant_id: str,
        expected_delta: ExpectedDelta,
        required_resources: ResourceVector,
        evidence_refs: List[str],
        reversibility: ReversibilityClass,
        vital_hp: int = VITAL_MAX_HP
    ):
        self.action_id = action_id
        self.source_state_version = source_state_version
        self.generated_at_ns = generated_at_ns
        self.valid_until_ns = valid_until_ns
        self.action_type = action_type
        self.target_tenant_id = target_tenant_id
        self.expected_delta = expected_delta
        self.required_resources = required_resources
        self.evidence_refs = evidence_refs
        self.reversibility = reversibility
        self.vital_hp = vital_hp

    def is_valid_at(self, current_version: StateVersion, now_ns: int) -> Tuple[bool, Optional[str]]:
        """
        Validates state version lineage and validity time window.
        """
        if not self.source_state_version.is_compatible_with(current_version):
            return False, f"StateVersion mismatch: candidate was generated for {self.source_state_version}, current is {current_version}"

        if now_ns > self.valid_until_ns:
            elapsed_ms = (now_ns - self.valid_until_ns) / 1e6
            return False, f"Action validity window expired by {elapsed_ms:.2f} ms (now_ns={now_ns} > valid_until_ns={self.valid_until_ns})"

        if self.vital_hp != VITAL_MAX_HP:
            return False, f"VITAL_MAX_HP invariant breach: expected {VITAL_MAX_HP}, candidate has {self.vital_hp}"

        return True, None

    def action_signature(self) -> str:
        return f"{self.action_type}:{self.target_tenant_id}:{self.reversibility.value}"

    def to_dict(self) -> Dict[str, Any]:
        return {
            "action_id": self.action_id,
            "source_state_version": self.source_state_version.to_dict(),
            "generated_at_ns": self.generated_at_ns,
            "valid_until_ns": self.valid_until_ns,
            "action_type": self.action_type,
            "target_tenant_id": self.target_tenant_id,
            "expected_delta": self.expected_delta.to_dict(),
            "required_resources": self.required_resources.to_dict(),
            "evidence_refs": self.evidence_refs,
            "reversibility": self.reversibility.value,
            "vital_hp": self.vital_hp
        }


class SafetyGate:
    """
    Deterministic safety authority decomposing verification into four disjoint domains:
      1. MemorySafety
      2. ResourceSafety
      3. PhysicalSafety
      4. SystemInvariants
    """

    def __init__(self, policy: Optional[DynamicSafetyPolicy] = None):
        self.policy = policy or GLOBAL_POLICY_REGISTRY.get_safety_policy()

    def evaluate(
        self,
        candidate: CandidateAction,
        current_state_version: StateVersion,
        current_envelope: Optional[ResourceEvidenceEnvelope],
        now_ns: int
    ) -> SafetyProof:
        violations: List[SafetyViolationRecord] = []

        # 1. StateVersion & Action Expiration Pre-Flight
        is_valid, err_msg = candidate.is_valid_at(current_state_version, now_ns)
        if not is_valid:
            violations.append(SafetyViolationRecord(
                tier=SafetyTier.SYSTEM_INVARIANTS,
                violation_code="INVALID_STATE_OR_EXPIRED",
                details=err_msg or "Candidate validity check failed",
                measured_value=candidate.valid_until_ns,
                threshold_value=now_ns,
                timestamp_ns=now_ns
            ))

        # 2. MemorySafety: bounds, pointer lengths, zero-copy safety
        mem_ok = bool(candidate.target_tenant_id and len(candidate.target_tenant_id) < 128)
        memory_check = {
            "tenant_id_length": len(candidate.target_tenant_id),
            "max_tenant_id_length": 128,
            "pointer_bounds_valid": mem_ok,
            "zero_copy_descriptor_valid": True
        }
        if not mem_ok:
            violations.append(SafetyViolationRecord(
                tier=SafetyTier.MEMORY_SAFETY,
                violation_code="BUFFER_BOUNDS_OVERFLOW",
                details="Target tenant identifier surpasses maximum allowable buffer length",
                measured_value=len(candidate.target_tenant_id),
                threshold_value=128,
                timestamp_ns=now_ns
            ))

        # 3. ResourceSafety: RAM headroom, OOM risk
        res_ok = True
        headroom_bytes = self.policy.memory_headroom_bytes("host-default")
        current_mem_rss = 0
        if current_envelope and "memory_rss_bytes" in current_envelope.canonical_normalized:
            current_mem_rss = int(current_envelope.canonical_normalized["memory_rss_bytes"].value)

        projected_req_mem = candidate.required_resources.memory_bytes
        resource_check = {
            "current_mem_rss_bytes": current_mem_rss,
            "requested_mem_bytes": projected_req_mem,
            "required_headroom_bytes": headroom_bytes
        }
        if projected_req_mem > 32 * 1024 * 1024 * 1024:  # 32 GB hard single-action limit
            res_ok = False
            violations.append(SafetyViolationRecord(
                tier=SafetyTier.RESOURCE_SAFETY,
                violation_code="EXCESSIVE_RESOURCE_REQUEST",
                details="Requested memory exceeds single-action safety ceiling",
                measured_value=projected_req_mem,
                threshold_value=32 * 1024 * 1024 * 1024,
                timestamp_ns=now_ns
            ))

        # 4. PhysicalSafety: Silicon thermal & electrical power limits
        phys_ok = True
        curr_thermal = 45.0
        curr_power = 15.0
        if current_envelope:
            if "temperature_celsius" in current_envelope.canonical_normalized:
                curr_thermal = float(current_envelope.canonical_normalized["temperature_celsius"].value)
            if "package_power_watts" in current_envelope.canonical_normalized:
                curr_power = float(current_envelope.canonical_normalized["package_power_watts"].value)

        thermal_ceiling = self.policy.thermal_limit("host-default", "standard", candidate.expected_delta.confidence)
        power_ceiling = self.policy.power_ceiling_watts("host-default", "standard")

        physical_check = {
            "current_thermal_celsius": curr_thermal,
            "thermal_limit_celsius": thermal_ceiling,
            "current_power_watts": curr_power,
            "power_ceiling_watts": power_ceiling
        }

        if curr_thermal >= thermal_ceiling:
            phys_ok = False
            violations.append(SafetyViolationRecord(
                tier=SafetyTier.PHYSICAL_SAFETY,
                violation_code="THERMAL_CEILING_BREACH",
                details=f"Current hardware temperature ({curr_thermal:.1f}°C) exceeds dynamic safety limit ({thermal_ceiling:.1f}°C)",
                measured_value=curr_thermal,
                threshold_value=thermal_ceiling,
                timestamp_ns=now_ns
            ))

        if curr_power >= power_ceiling:
            phys_ok = False
            violations.append(SafetyViolationRecord(
                tier=SafetyTier.PHYSICAL_SAFETY,
                violation_code="POWER_CEILING_BREACH",
                details=f"Current package power ({curr_power:.1f}W) exceeds dynamic electrical limit ({power_ceiling:.1f}W)",
                measured_value=curr_power,
                threshold_value=power_ceiling,
                timestamp_ns=now_ns
            ))

        # 5. SystemInvariants: VITAL_MAX_HP == 6 & State Continuity
        invariants_ok = (candidate.vital_hp == VITAL_MAX_HP) and is_valid
        invariants_check = {
            "vital_hp": candidate.vital_hp,
            "vital_max_hp_rule": VITAL_MAX_HP,
            "state_version_continuous": is_valid
        }
        if candidate.vital_hp != VITAL_MAX_HP:
            violations.append(SafetyViolationRecord(
                tier=SafetyTier.SYSTEM_INVARIANTS,
                violation_code="VITAL_MAX_HP_CORRUPTED",
                details=f"Core system invariant breach: vital_hp must strictly be {VITAL_MAX_HP}",
                measured_value=candidate.vital_hp,
                threshold_value=VITAL_MAX_HP,
                timestamp_ns=now_ns
            ))

        # Final Safety Verdict: VETO if ANY violation exists across the 4 domains
        verdict = SafetyVerdictType.PASS if len(violations) == 0 else SafetyVerdictType.VETO

        return SafetyProof(
            verdict=verdict,
            memory_safety_check=memory_check,
            resource_safety_check=resource_check,
            physical_safety_check=physical_check,
            system_invariants_check=invariants_check,
            policy_version=self.policy.policy_version,
            evaluated_at_ns=now_ns,
            violations=violations
        )


class EvidenceGate:
    """
    Epistemic lattice evaluator.
    SUFFICIENT is NOT derived from confidence alone.
    Requires evaluation of:
      - freshness
      - provenance
      - cross-sensor consistency
      - sample count
      - calibration error
      - domain compatibility
      - state-version compatibility
      - clock validity
    """

    def __init__(self, policy: Optional[DynamicEvidencePolicy] = None):
        self.policy = policy or GLOBAL_POLICY_REGISTRY.get_evidence_policy()

    def evaluate(
        self,
        candidate: CandidateAction,
        supporting_envelopes: List[ResourceEvidenceEnvelope],
        now_ns: int
    ) -> EvidenceProof:
        gaps: List[Dict[str, Any]] = []
        contradictions: List[Dict[str, Any]] = []

        # 1. Sample Count Evaluation
        sample_count = len(supporting_envelopes)
        sample_ok = sample_count >= self.policy.min_sample_count
        sample_eval = {
            "observed_samples": sample_count,
            "required_samples": self.policy.min_sample_count,
            "is_sufficient": sample_ok
        }
        if not sample_ok:
            gaps.append({
                "reason": "INSUFFICIENT_SAMPLE_COUNT",
                "details": f"Observed {sample_count} evidence envelopes, minimum required is {self.policy.min_sample_count}"
            })

        # 2. Freshness & Expiration Evaluation
        stale_count = 0
        expired_count = 0
        fresh_count = 0
        for env in supporting_envelopes:
            env_time_ns = int(env.wall_timestamp_utc * 1e9)
            age_ns = max(0, now_ns - env_time_ns)
            if age_ns > self.policy.max_acceptable_age_ns:
                stale_count += 1
            for metric_key, val in env.canonical_normalized.items():
                st = val.get_validity_state(now_ns)
                if st == ValidityState.EXPIRED:
                    expired_count += 1
                elif st == ValidityState.FRESH:
                    fresh_count += 1

        freshness_ok = (stale_count == 0) and (expired_count == 0) and (fresh_count > 0)
        freshness_eval = {
            "fresh_values_count": fresh_count,
            "stale_envelopes_count": stale_count,
            "expired_values_count": expired_count,
            "max_acceptable_age_ns": self.policy.max_acceptable_age_ns,
            "is_fresh": freshness_ok
        }
        if not freshness_ok:
            gaps.append({
                "reason": "EVIDENCE_STALE_OR_EXPIRED",
                "details": f"Found {stale_count} stale envelopes and {expired_count} expired epistemic values. Expired data must not participate in decisions."
            })

        # 3. Provenance & Adapter Integrity
        trusted_adapters = {"KvmQemuAdapter", "HyperVAdapter", "CppHardwareProbe", "IHypervisorAdapter"}
        provenance_ok = all(
            any(t in env.provenance for t in trusted_adapters) for env in supporting_envelopes
        ) if supporting_envelopes else False

        provenance_eval = {
            "provenances": [env.provenance for env in supporting_envelopes],
            "trusted_registry_match": provenance_ok
        }
        if not provenance_ok:
            gaps.append({
                "reason": "UNTRUSTED_OR_UNKNOWN_PROVENANCE",
                "details": "One or more evidence envelopes originate from unverified sources."
            })

        # 4. Cross-Sensor Consistency & Contradiction Detection
        # Check if identical metric domain measured by multiple sensors diverges beyond tolerance
        sensors_by_domain: Dict[str, List[float]] = {}
        for env in supporting_envelopes:
            for d_name, ep_val in env.canonical_normalized.items():
                if isinstance(ep_val.value, (int, float)):
                    sensors_by_domain.setdefault(d_name, []).append(float(ep_val.value))

        for domain, measurements in sensors_by_domain.items():
            if len(measurements) >= 2:
                mean_val = sum(measurements) / len(measurements)
                if mean_val > 1e-4:
                    max_dev = max(abs(m - mean_val) for m in measurements)
                    dev_pct = (max_dev / mean_val) * 100.0
                    if dev_pct > self.policy.max_sensor_divergence_pct:
                        contradictions.append({
                            "domain": domain,
                            "measurements": measurements,
                            "divergence_pct": round(dev_pct, 2),
                            "max_allowed_divergence_pct": self.policy.max_sensor_divergence_pct,
                            "explanation": f"Cross-sensor divergence ({dev_pct:.1f}%) exceeds calibration threshold"
                        })

        consistency_ok = len(contradictions) == 0
        cross_sensor_eval = {
            "domains_analyzed": list(sensors_by_domain.keys()),
            "contradictions_found": len(contradictions),
            "is_consistent": consistency_ok
        }

        # 5. Calibration Error Evaluation
        max_obs_cal_error = 0.0
        for env in supporting_envelopes:
            for ep_val in env.canonical_normalized.values():
                if ep_val.calibration_error > max_obs_cal_error:
                    max_obs_cal_error = ep_val.calibration_error

        calibration_ok = max_obs_cal_error <= self.policy.max_calibration_error
        calibration_eval = {
            "max_observed_calibration_error": max_obs_cal_error,
            "max_allowable_calibration_error": self.policy.max_calibration_error,
            "is_calibrated": calibration_ok
        }
        if not calibration_ok:
            gaps.append({
                "reason": "POOR_CALIBRATION_ERROR",
                "details": f"Instrument calibration error ({max_obs_cal_error:.3f}) exceeds threshold ({self.policy.max_calibration_error:.3f})"
            })

        # 6. Domain Compatibility
        domain_ok = True
        domain_eval = {"action_domains": ["cpu", "memory"], "compatible": domain_ok}

        # 7. State Version Lineage Evaluation
        state_ver_ok = all(
            env.state_version.major == candidate.source_state_version.major
            for env in supporting_envelopes
        ) if supporting_envelopes else False
        state_ver_eval = {
            "candidate_source_version": candidate.source_state_version.to_dict(),
            "compatible": state_ver_ok
        }
        if not state_ver_ok:
            gaps.append({
                "reason": "STATE_VERSION_LINEAGE_MISMATCH",
                "details": "Supporting evidence belongs to a disjoint or diverged state version"
            })

        # 8. Clock Domain Validity
        clocks = {env.clock_domain_id for env in supporting_envelopes}
        clock_ok = len(clocks) <= 1
        clock_eval = {
            "observed_clock_domains": list(clocks),
            "clock_synchrony_valid": clock_ok
        }
        if not clock_ok:
            contradictions.append({
                "domain": "clock_synchrony",
                "clock_domains": list(clocks),
                "explanation": "Cross-host monotonic timestamps mixed without causal parent synchronization"
            })

        # Derive Evidence Verdict:
        # CONTRADICTORY dominates INSUFFICIENT
        if len(contradictions) > 0:
            verdict = EvidenceVerdictType.CONTRADICTORY
        elif not sample_ok or not freshness_ok or not provenance_ok or not calibration_ok or not state_ver_ok:
            verdict = EvidenceVerdictType.INSUFFICIENT
        else:
            verdict = EvidenceVerdictType.SUFFICIENT

        return EvidenceProof(
            verdict=verdict,
            freshness_eval=freshness_eval,
            provenance_eval=provenance_eval,
            cross_sensor_consistency=cross_sensor_eval,
            sample_count_eval=sample_eval,
            calibration_error_eval=calibration_eval,
            domain_eval=domain_eval,
            state_version_eval=state_ver_eval,
            clock_validity_eval=clock_eval,
            evaluated_at_ns=now_ns,
            contradictions=contradictions,
            gaps=gaps
        )


class DualAuthorityGate:
    """
    Combines SafetyGate and EvidenceGate deterministically.
    Never collapses them into a single verifier.
    """

    def __init__(
        self,
        safety_gate: Optional[SafetyGate] = None,
        evidence_gate: Optional[EvidenceGate] = None
    ):
        self.safety_gate = safety_gate or SafetyGate()
        self.evidence_gate = evidence_gate or EvidenceGate()

    def arbitrate(
        self,
        candidate: CandidateAction,
        current_state_version: StateVersion,
        supporting_envelopes: List[ResourceEvidenceEnvelope],
        now_ns: Optional[int] = None
    ) -> AuthorityProofBundle:
        eval_time_ns = now_ns or int(time.time() * 1e9)

        primary_env = supporting_envelopes[0] if supporting_envelopes else None

        # 1. Evaluate Safety Gate (Binary: PASS or VETO)
        safety_proof = self.safety_gate.evaluate(
            candidate=candidate,
            current_state_version=current_state_version,
            current_envelope=primary_env,
            now_ns=eval_time_ns
        )

        # 2. Evaluate Evidence Gate (SUFFICIENT, INSUFFICIENT, CONTRADICTORY)
        evidence_proof = self.evidence_gate.evaluate(
            candidate=candidate,
            supporting_envelopes=supporting_envelopes,
            now_ns=eval_time_ns
        )

        # 3. Canonical Authority Verdict Function f(SafetyGate, EvidenceGate)
        if safety_proof.verdict == SafetyVerdictType.VETO:
            verdict = AuthorityVerdictType.VETO_SAFETY_BREACH
            lifecycle_action = "REJECT_NOOP"  # Pre-actuation veto -> zero mutation, zero compensation
        elif evidence_proof.verdict == EvidenceVerdictType.CONTRADICTORY:
            verdict = AuthorityVerdictType.QUARANTINE_CONTRADICTORY_EVIDENCE
            lifecycle_action = "QUARANTINE_AND_RECALIBRATE"
        elif evidence_proof.verdict == EvidenceVerdictType.INSUFFICIENT:
            verdict = AuthorityVerdictType.DEFER_INSUFFICIENT_EVIDENCE
            lifecycle_action = "TRIGGER_ACTIVE_MICRO_PROBE"
        else:
            verdict = AuthorityVerdictType.COMMIT_APPROVED
            # Sprint A Constraint: READ-ONLY TELEMETRY / SHADOW PREDICTION.
            # Record WOULD_COMMIT without actuating OS changes!
            lifecycle_action = "WOULD_COMMIT"

        return AuthorityProofBundle(
            verdict=verdict,
            safety_proof=safety_proof,
            evidence_proof=evidence_proof,
            policy_version=safety_proof.policy_version,
            state_version=current_state_version,
            evaluated_at_ns=eval_time_ns,
            evidence_refs=candidate.evidence_refs,
            action_id=candidate.action_id,
            lifecycle_action=lifecycle_action
        )
