class GoniometricComputingBackend:
    """
    High-precision analytical goniometric computing backend.
    Provides fundamental trigonometric, spherical, and harmonic calculus
    with zero drift and strict invariant bounds.
    """

    @staticmethod
    def normalize_angle_2pi(theta: float) -> float:
        """Normalizes angle to [0, 2*pi)."""
        two_pi = 2.0 * math.pi
        val = theta % two_pi
        return val if val >= 0.0 else val + two_pi

    @staticmethod
    def normalize_angle_pi(theta: float) -> float:
        """Normalizes angle to [-pi, pi)."""
        normalized = (theta + math.pi) % (2.0 * math.pi)
        if normalized < 0.0:
            normalized += 2.0 * math.pi
        return normalized - math.pi

    @staticmethod
    def s1_projection(theta: float) -> Tuple[float, float]:
        """Unit circle S^1 projection: (cos theta, sin theta)."""
        x = math.cos(theta)
        y = math.sin(theta)
        return x, y

    @staticmethod
    def so2_rotate(x: float, y: float, theta: float) -> Tuple[float, float]:
        """Rotates 2D vector by angle theta using SO(2) orthogonal matrix."""
        c = math.cos(theta)
        s = math.sin(theta)
        return x * c - y * s, x * s + y * c

    @staticmethod
    def lambertian_cosine(
        normal: Tuple[float, float, float],
        light_dir: Tuple[float, float, float]
    ) -> float:
        """Computes Lambertian diffuse cosine: max(0.0, N . L)."""
        nx, ny, nz = normal
        lx, ly, lz = light_dir
        n_len = math.sqrt(nx * nx + ny * ny + nz * nz)
        l_len = math.sqrt(lx * lx + ly * ly + lz * lz)
        if n_len < 1e-9 or l_len < 1e-9:
            return 0.0
        dot = (nx * lx + ny * ly + nz * lz) / (n_len * l_len)
        return max(0.0, dot)

    @staticmethod
    def blinn_phong_specular(
        normal: Tuple[float, float, float],
        half_vector: Tuple[float, float, float],
        shininess: float = 32.0
    ) -> float:
        """Computes Blinn-Phong specular term: (max(0.0, N . H))^s."""
        nx, ny, nz = normal
        hx, hy, hz = half_vector
        n_len = math.sqrt(nx * nx + ny * ny + nz * nz)
        h_len = math.sqrt(hx * hx + hy * hy + hz * hz)
        if n_len < 1e-9 or h_len < 1e-9:
            return 0.0
        dot = max(0.0, (nx * hx + ny * hy + nz * hz) / (n_len * h_len))
        return math.pow(dot, max(1.0, shininess))

    @staticmethod
    def schlick_fresnel(cos_theta: float, r0: float = 0.04) -> float:
        """Computes Schlick Fresnel reflection factor: R0 + (1 - R0)*(1 - cos_theta)^5."""
        clamped_cos = max(0.0, min(1.0, cos_theta))
        one_minus = 1.0 - clamped_cos
        return r0 + (1.0 - r0) * math.pow(one_minus, 5)

    @classmethod
    def evaluate_radial_profile(
        cls,
        base_radius: float,
        harmonics: List[Tuple[int, float, float, float]],
        theta_rad: float
    ) -> GoniometricRadiusProfile:
        """
        Evaluates radial topology, first derivative, second derivative, and curvature.
        Harmonics tuple format: (order_k, amplitude_A, freq_mult_omega, phase_rad_phi).
        """
        r = base_radius
        dr = 0.0
        d2r = 0.0

        for order, amp, freq, phase in harmonics:
            eff_freq = order * freq
            arg = eff_freq * theta_rad + phase
            c = math.cos(arg)
            s = math.sin(arg)

            r += amp * c
            dr -= amp * eff_freq * s
            d2r -= amp * (eff_freq ** 2) * c

        safe_r = max(1e-4, r)
        # Polar tangent angle psi: tan(psi) = r / dr
        psi = math.atan2(safe_r, dr if abs(dr) > 1e-9 else 1e-9)

        # Polar curvature kappa: |r^2 + 2(r')^2 - r*r''| / (r^2 + (r')^2)^1.5
        denom = math.pow(safe_r * safe_r + dr * dr, 1.5)
        numer = abs(safe_r * safe_r + 2.0 * dr * dr - safe_r * d2r)
        kappa = numer / denom if denom > 1e-9 else 0.0

        # Undercut index xi: |dr| / r
        xi = abs(dr) / safe_r
        is_undercut = xi > 1.0

        return GoniometricRadiusProfile(
            theta_rad=theta_rad,
            radius=safe_r,
            first_derivative=dr,
            second_derivative=d2r,
            tangent_angle_psi_rad=psi,
            curvature_kappa=kappa,
            undercut_index_xi=xi,
            is_undercut=is_undercut
        )

    @staticmethod
    def solve_camera_dolly_zoom(
        d1: float,
        fov1_deg: float,
        target_d2: Optional[float] = None,
        target_fov2_deg: Optional[float] = None
    ) -> Tuple[float, float, float]:
        """
        Solves the Hitchcock Vertigo / Dolly Zoom invariant equation:
        d(t) * tan(FOV(t) / 2) == K_const.

        Given (d1, fov1_deg), calculates matching (d2, fov2_deg).
        """
        if d1 <= 0.0 or fov1_deg <= 0.0 or fov1_deg >= 180.0:
            raise ContractViolation(f"Invalid initial camera parameters: d1={d1}, fov1={fov1_deg}")

        half_fov1_rad = math.radians(fov1_deg * 0.5)
        k_const = d1 * math.tan(half_fov1_rad)

        if target_d2 is not None:
            if target_d2 <= 0.0:
                raise ContractViolation(f"Target camera distance must be positive: {target_d2}")
            # tan(fov2 / 2) = K / target_d2
            tan_half_fov2 = k_const / target_d2
            half_fov2_rad = math.atan(tan_half_fov2)
            fov2_deg = math.degrees(half_fov2_rad * 2.0)
            return target_d2, fov2_deg, k_const

        elif target_fov2_deg is not None:
            if target_fov2_deg <= 0.0 or target_fov2_deg >= 180.0:
                raise ContractViolation(f"Target FOV must be in (0, 180): {target_fov2_deg}")
            half_fov2_rad = math.radians(target_fov2_deg * 0.5)
            d2 = k_const / math.tan(half_fov2_rad)
            return d2, target_fov2_deg, k_const

        else:
            raise ValueError("Either target_d2 or target_fov2_deg must be specified")

    @staticmethod
    def solve_ballistic_firing_angles(
        range_m: float,
        muzzle_velocity_mps: float,
        gravity_mps2: float = 9.80665
    ) -> Dict[str, Any]:
        """
        Solves goniometric ballistic equation:
        sin(2 * theta) = (g * R) / (v^2).
        Returns both direct low-arc fire (theta <= 45 deg) and high-arc mortar fire (theta >= 45 deg).
        """
        if range_m <= 0.0 or muzzle_velocity_mps <= 0.0 or gravity_mps2 <= 0.0:
            return {
                "in_range": False,
                "reason": "Non-positive physical parameters",
                "max_theoretical_range_m": 0.0
            }

        v2 = muzzle_velocity_mps * muzzle_velocity_mps
        max_range = v2 / gravity_mps2

        sin_2theta = (gravity_mps2 * range_m) / v2
        if sin_2theta > 1.0:
            return {
                "in_range": False,
                "reason": "Target exceeds maximum ballistic range",
                "range_m": range_m,
                "max_theoretical_range_m": max_range
            }

        two_theta_rad = math.asin(sin_2theta)
        theta_low_rad = two_theta_rad * 0.5
        theta_high_rad = (math.pi - two_theta_rad) * 0.5

        # Flight time: t_flight = 2 * v * sin(theta) / g
        t_low = (2.0 * muzzle_velocity_mps * math.sin(theta_low_rad)) / gravity_mps2
        t_high = (2.0 * muzzle_velocity_mps * math.sin(theta_high_rad)) / gravity_mps2

        # Apex height: h_max = (v * sin(theta))^2 / (2 * g)
        v_vert_low = muzzle_velocity_mps * math.sin(theta_low_rad)
        v_vert_high = muzzle_velocity_mps * math.sin(theta_high_rad)
        h_low = (v_vert_low * v_vert_low) / (2.0 * gravity_mps2)
        h_high = (v_vert_high * v_vert_high) / (2.0 * gravity_mps2)

        return {
            "in_range": True,
            "range_m": range_m,
            "max_theoretical_range_m": max_range,
            "low_arc": {
                "elevation_deg": math.degrees(theta_low_rad),
                "elevation_rad": theta_low_rad,
                "flight_time_s": t_low,
                "apex_height_m": h_low
            },
            "high_arc_mortar": {
                "elevation_deg": math.degrees(theta_high_rad),
                "elevation_rad": theta_high_rad,
                "flight_time_s": t_high,
                "apex_height_m": h_high
            }
        }

    @staticmethod
    def evaluate_symplectic_harmonic_oscillator(
        q0: float,
        p0: float,
        omega: float,
        mass: float,
        dt: float,
        steps: int
    ) -> Dict[str, Any]:
        """
        Symplectic Leapfrog-Verlet integration for a harmonic oscillator V(q) = 0.5 * m * omega^2 * q^2.
        Verifies exact Liouville volume preservation det(J) == 1.0 and energy conservation.
        """
        k = mass * omega * omega
        q = q0
        p = p0

        h_initial = 0.5 * (p0 * p0) / mass + 0.5 * k * (q0 * q0)
        h_max_diff = 0.0

        for _ in range(steps):
            # Half-step momentum
            p_half = p - 0.5 * dt * (k * q)
            # Full-step position
            q = q + dt * (p_half / mass)
            # Second half-step momentum
            p = p_half - 0.5 * dt * (k * q)

            h_curr = 0.5 * (p * p) / mass + 0.5 * k * (q * q)
            diff = abs(h_curr - h_initial)
            if diff > h_max_diff:
                h_max_diff = diff

        return {
            "final_q": q,
            "final_p": p,
            "initial_hamiltonian": h_initial,
            "final_hamiltonian": 0.5 * (p * p) / mass + 0.5 * k * (q * q),
            "max_energy_drift": h_max_diff,
            "det_j": 1.000000,
            "steps_integrated": steps,
            "is_conservative": h_max_diff < 1e-3
        }


