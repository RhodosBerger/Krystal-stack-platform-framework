    def __init__(self, vital_max_hp: int = VITAL_MAX_HP) -> None:
        if vital_max_hp != VITAL_MAX_HP:
            raise ContractViolation(f"Constitutional invariant breach in GoniometricProposerKernel: {vital_max_hp}")
        self.vital_max_hp = vital_max_hp
        self.backend = GoniometricComputingBackend()
        self._proposal_counter = 0
        self._proposal_history: List[GoniometricActionProposal] = []

    def _next_proposal_id(self, prefix: str) -> str:
        self._proposal_counter += 1
        return f"PROP-GONIO-{prefix}-{self._proposal_counter:05d}"

    def propose_trajectory_motion(
        self,
        current_pos: Tuple[float, float, float],
        target_angle_rad: float,
        angular_speed_rad_per_s: float,
        dt_s: float = 0.016667
    ) -> GoniometricActionProposal:
        """
        Proposes a smooth symplectic trajectory motion vector over time step dt_s.
        Uses SO(2) rotation in the horizontal plane and evaluates harmonic phase velocity.
        """
        cx, cy, cz = current_pos
        norm_target = self.backend.normalize_angle_2pi(target_angle_rad)
        current_angle = self.backend.normalize_angle_2pi(math.atan2(cy, cx) if (cx != 0 or cy != 0) else 0.0)

        angle_delta = self.backend.normalize_angle_pi(norm_target - current_angle)
        step_angle = math.copysign(min(abs(angle_delta), angular_speed_rad_per_s * dt_s), angle_delta)

        # Rotate horizontal coordinates
        nx, ny = self.backend.so2_rotate(cx, cy, step_angle)
        # Momentum vector: p = v = d(pos) / dt
        px = (nx - cx) / dt_s if dt_s > 0 else 0.0
        py = (ny - cy) / dt_s if dt_s > 0 else 0.0

        prop_id = self._next_proposal_id("TRAJ")
        metrics = {
            "start_angle_rad": current_angle,
            "target_angle_rad": norm_target,
            "step_angle_rad": step_angle,
            "next_x": nx,
            "next_y": ny,
            "velocity_px": px,
            "velocity_py": py,
            "det_j": 1.0
        }

        prop = GoniometricActionProposal(
            proposal_id=prop_id,
            category=GoniometricProposalCategory.TRAJECTORY_MOTION,
            target_subsystem="L2_SPATIAL_SYMPLECTIC",
            target_parameter="SYMPLECTIC_PHASE_VECTOR",
            current_value=current_angle,
            proposed_delta=step_angle,
            proposed_value=current_angle + step_angle,
            goniometric_rationale=(
                f"Harmonic SO(2) orbital step: delta_theta={step_angle:.5f} rad, "
                f"tangential speed={angular_speed_rad_per_s:.3f} rad/s preserving det(J)=1.0"
            ),
            mathematical_metrics=metrics,
            evidence_claim="SO(2) rotation preserves symplectic area on horizontal manifold",
            falsification_condition="det(J) != 1.0 or angular velocity exceeds mechanical limit"
        )

        self._proposal_history.append(prop)
        return prop

    def propose_camera_dolly_zoom(
        self,
        current_dist: float,
        current_fov_deg: float,
        target_dist: float
    ) -> GoniometricActionProposal:
        """
        Proposes camera FOV change matched to target distance change to maintain
        the Vertigo Dolly Zoom invariant: d * tan(FOV / 2) == const.
        """
        d2, fov2_deg, k_const = self.backend.solve_camera_dolly_zoom(
            d1=current_dist,
            fov1_deg=current_fov_deg,
            target_d2=target_dist
        )

        prop_id = self._next_proposal_id("ZOOM")
        fov_delta = fov2_deg - current_fov_deg
        metrics = {
            "current_dist": current_dist,
            "target_dist": d2,
            "current_fov_deg": current_fov_deg,
            "proposed_fov_deg": fov2_deg,
            "vertigo_invariant_k": k_const
        }

        prop = GoniometricActionProposal(
            proposal_id=prop_id,
            category=GoniometricProposalCategory.CAMERA_VERTIGO_ZOOM,
            target_subsystem="L1_CHRONO_CAMERA_RIG",
            target_parameter="CAMERA_FIELD_OF_VIEW_DEG",
            current_value=current_fov_deg,
            proposed_delta=fov_delta,
            proposed_value=fov2_deg,
            goniometric_rationale=(
                f"Vertigo Dolly Zoom invariant preserved: d * tan(FOV/2) = {k_const:.4f}. "
                f"Moving camera from {current_dist:.2f}m to {d2:.2f}m requires FOV {fov2_deg:.2f} deg."
            ),
            mathematical_metrics=metrics,
            evidence_claim="Hitchcock-Vertigo goniometric invariant maintains constant subject screen height",
            falsification_condition="Abs(d2 * tan(FOV2/2) - K) > 1e-4 or FOV out of bounds (0, 180)"
        )

        self._proposal_history.append(prop)
        return prop

