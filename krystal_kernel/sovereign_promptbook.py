def canonical_recipe_json(
    recipe_id: str,
    title: str,
    category: str,
    system_directive: str,
    user_template: str,
    input_slots: List[str],
    bound_invariants: List[str],
    expected_output_format: str,
    falsification_condition: str,
    schema_version: str,
    vital_max_hp: int
) -> bytes:
    """
    Produces deterministic canonical JSON serialization for HMAC integrity signing.
    Guarantees: RecipeChanged => DigestChanged across all functional attributes.
    """
    payload = {
        "bound_invariants": sorted(bound_invariants),
        "category": category,
        "expected_output_format": expected_output_format,
        "falsification_condition": falsification_condition,
        "input_slots": sorted(input_slots),
        "recipe_id": recipe_id,
        "schema_version": schema_version,
        "system_directive": system_directive,
        "title": title,
        "user_template": user_template,
        "vital_max_hp": vital_max_hp
    }
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")


